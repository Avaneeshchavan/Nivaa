require('tsx/cjs')
const assert = require('node:assert/strict')
const { parseCatalog, readJsonCatalog, inspectCatalog, normalizeBrandSearch } = require('../lib/medicines/brand-preflight.ts')
const rows = Array.from({ length: 200 }, (_, i) => ({ id: String(i), name: `Synthetic fixture ${i} 0.5 mg`, manufacturer_name: 'Synthetic company', type: 'tablet', Is_discontinued: 'false', short_composition1: 'Synthetic ingredient 0.5 mg', short_composition2: '' }))
assert.equal(inspectCatalog(rows).accepted, 200)
assert.equal(inspectCatalog([...rows, rows[0]]).duplicateCandidates, 1)
assert.equal(inspectCatalog([{ ...rows[0], Is_discontinued: 'true' }]).discontinued, 1)
assert.equal(inspectCatalog([{ ...rows[0], Is_discontinued: 'unknown' }]).reviewRows.length, 1)
assert.equal(inspectCatalog([{ ...rows[0], manufacturer_name: '' }]).reviewRows.length, 1)
assert.equal(inspectCatalog([rows[0], { ...rows[0], name: 'Synthetic fixture 0 05 mg' }]).accepted, 2, 'never conflate decimal strengths')
assert.equal(inspectCatalog([{ brand_code: 'fixture' }]).format, 'UNMAPPED')
assert.deepEqual(parseCatalog('\uFEFFname,company\r\n"A, B","C ""D"""\r\n"A\nB",C', ','), [{ name: 'A, B', company: 'C "D"' }, { name: 'A\nB', company: 'C' }])
assert.deepEqual(parseCatalog('id\tname\n1\tFixture', '\t'), [{ id: '1', name: 'Fixture' }])
for (const text of ['a,a\n1,2', 'a,b\n1', 'a,b\n"unclosed,2', 'a,b\n"closed"bad,2']) assert.throws(() => parseCatalog(text, ','))
assert.throws(() => readJsonCatalog('[{"name":{"nested":"bad"}}]'))
assert.deepEqual(readJsonCatalog('[{"id":1,"name":"Fixture","flag":false,"blank":null}]'), [{ id: '1', name: 'Fixture', flag: 'false', blank: '' }])
assert.equal(normalizeBrandSearch('  Ｏｎｄｅｍ-MD '), 'ondem md')
assert.equal(normalizeBrandSearch('Uprise D3'), 'uprise d3')
console.log('PASS: 200 synthetic rows, CSV/TSV/JSON, BOM/quotes/newlines, malformed input, discontinued flags, duplicate candidates and distinct decimal strengths')
const fs = require('node:fs/promises')
const { spawnSync } = require('node:child_process')
const path = require('node:path')
;(async () => {
  const reportPath = 'docs/IMPORT_REPORT.md'
  const original = await fs.readFile(reportPath, 'utf8')
  const directory = await fs.mkdtemp('data/brands/.preflight-test-')
  const input = path.join(directory, 'synthetic.json')
  try {
    await fs.writeFile(input, JSON.stringify(rows))
    const run = file => spawnSync(process.execPath, ['--import', 'tsx', 'scripts/preflight-brands.ts', file], { encoding: 'utf8' })
    assert.equal(run(input).status, 0)
    const report = await fs.readFile(reportPath, 'utf8')
    assert.match(report, /input rows: 200/)
    assert.match(report, /Database bytes added: 0/)
    assert.doesNotMatch(report, /Synthetic ingredient/)
    assert.equal(run('package.json').status, 1, 'deny paths outside local catalog folder')
    await fs.writeFile(input, '{malformed')
    assert.equal(run(input).status, 1)
    assert.equal(await fs.readFile(reportPath, 'utf8'), report, 'failed input cannot replace the previous report')
    console.log('PASS: real CLI report, raw-content omission, path boundary, malformed input and previous-report preservation')
  } finally {
    await fs.writeFile(reportPath, original)
    await fs.rm(directory, { recursive: true, force: true })
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
